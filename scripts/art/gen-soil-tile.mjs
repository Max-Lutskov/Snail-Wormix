// Generates public/art/soil-tile.svg: a seamless tile of big outlined soil clods with 3-tone
// volume, the same technique and palette as the bridge map (gen-bridge.mjs), for generated hills.
// Clods sit on a brick grid that divides the tile exactly, and every clod is also drawn shifted by
// ±tile so the ones crossing an edge continue on the other side. Rows are drawn bottom to top over
// the whole wrapped range, so overlaps match across the seams too.
// Seeded, so the output is stable. Usage: node scripts/art/gen-soil-tile.mjs public/art/soil-tile.svg
import { writeFileSync } from 'node:fs';

let seed = 4242;
const rnd = () => {
  seed |= 0;
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const r = (a, b) => a + (b - a) * rnd();
const f = (n) => Math.round(n * 10) / 10;
const OUT = '#2B1B12';

const COLS = 5;
const ROWS = 8;
const CELL_W = 96;
const CELL_H = 60;
const SIZE = COLS * CELL_W; // = ROWS * CELL_H = 480 (tokens.terrain.soilTileSize)
if (ROWS * CELL_H !== SIZE) throw new Error('tile must be square');

const SOIL = {
  base: ['#5C3A24', '#53331F', '#644129', '#583722'],
  shadow: '#3A2414',
  light: '#86593A',
};

/** Closed smooth blob path through jittered points around an ellipse at (0, 0). */
function blobPath(rx, ry, n = 8, jit = 0.14) {
  const pts = [];
  const a0 = r(0, Math.PI * 2);
  for (let i = 0; i < n; i++) {
    const a = a0 + (i / n) * Math.PI * 2 + r(-0.18, 0.18);
    const k = 1 + r(-jit, jit);
    pts.push([Math.cos(a) * rx * k, Math.sin(a) * ry * k]);
  }
  let d = `M${f(pts[0][0])},${f(pts[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = pts[(i - 1 + n) % n];
    const p1 = pts[i];
    const p2 = pts[(i + 1) % n];
    const p3 = pts[(i + 2) % n];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += ` C${f(c1[0])},${f(c1[1])} ${f(c2[0])},${f(c2[1])} ${f(p2[0])},${f(p2[1])}`;
  }
  return `${d}Z`;
}

// One clod per grid cell, defined once at the origin (a <symbol>-like <g> in <defs>).
const defs = [];
const cells = [];
for (let row = 0; row < ROWS; row++) {
  for (let col = 0; col < COLS; col++) {
    const id = `c${row}-${col}`;
    const rx = r(46, 62);
    const ry = r(32, 40);
    const d = blobPath(rx, ry);
    const base = SOIL.base[Math.floor(rnd() * SOIL.base.length)];
    const s = (k, dx, dy) => `transform="translate(${f(dx)},${f(dy)}) scale(${k})"`;
    defs.push(
      `<g id="${id}"><path d="${d}" fill="${SOIL.shadow}"/>` +
        `<path d="${d}" fill="${base}" ${s(0.9, -1, -ry * 0.1)}/>` +
        `<path d="${d}" fill="${SOIL.light}" opacity=".85" ${s(0.42, -rx * 0.22, -ry * 0.42)}/>` +
        `<path d="${d}" fill="none" stroke="${OUT}" stroke-width="3" stroke-linejoin="round"/></g>`,
    );
    cells.push({
      id,
      row,
      x: col * CELL_W + (row % 2) * (CELL_W / 2) + r(-16, 16),
      y: row * CELL_H + CELL_H / 2 + r(-10, 10),
    });
  }
}

// Draw the wrapped pattern: virtual rows from below the tile to above it, bottom first.
const uses = [];
for (let vr = ROWS; vr >= -1; vr--) {
  const row = ((vr % ROWS) + ROWS) % ROWS;
  const dy = ((vr - row) / ROWS) * SIZE;
  for (const c of cells.filter((cell) => cell.row === row)) {
    for (const dx of [-SIZE, 0, SIZE]) {
      uses.push(`<use href="#${c.id}" x="${f(c.x + dx)}" y="${f(c.y + dy)}"/>`);
    }
  }
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <!-- Seamless soil tile for generated hills (generated by scripts/art/gen-soil-tile.mjs): big outlined clods, same style as the bridge map. -->
  <defs>${defs.join('')}</defs>
  <rect width="${SIZE}" height="${SIZE}" fill="#2A1A10"/>
  ${uses.join('')}
</svg>
`;
writeFileSync(process.argv[2], svg);
console.log('written', svg.length, 'bytes');
